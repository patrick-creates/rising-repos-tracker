const fs = require("fs");
const path = require("path");

const DAY = 86400000;
const TOP_N = 10;
const MIN_STARS_FOR_PCT = 500; // below this, a few stars make huge percentages
const MAX_GAP_DAYS = 2;        // snapshot may be this many days before the target date

// ---- Dates (all UTC, "YYYY-MM-DD") ----
const toDate = (s) => new Date(s + "T00:00:00Z");
const toStr = (d) => d.toISOString().slice(0, 10);
const addDays = (s, n) => toStr(new Date(toDate(s).getTime() + n * DAY));

// ISO week of a date string -> { year, week, monday }
function isoWeek(s) {
  const d = toDate(s);
  const dow = (d.getUTCDay() + 6) % 7; // Mon=0
  const monday = addDays(s, -dow);
  const thursday = toDate(addDays(monday, 3));
  const year = thursday.getUTCFullYear();
  const jan1 = Date.UTC(year, 0, 1);
  const week = Math.floor((thursday - jan1) / DAY / 7) + 1;
  return { year, week, monday };
}

const weekLabel = ({ year, week }) => `${year}-W${String(week).padStart(2, "0")}`;

// Last ISO week whose following Monday already has data
function lastCompleteWeek(latestDate) {
  const { monday } = isoWeek(latestDate);
  return isoWeek(addDays(monday, -7));
}

// Latest snapshot on or before `date`, at most MAX_GAP_DAYS earlier
function snapshotAt(history, date) {
  let best = null;
  for (const e of history) if (e.date <= date && (!best || e.date > best.date)) best = e;
  if (!best) return null;
  return (toDate(date) - toDate(best.date)) / DAY <= MAX_GAP_DAYS ? best : null;
}

// ---- Report data ----
function weekStats(repos, histories, week) {
  const start = week.monday;
  const end = addDays(start, 7);
  const rows = [];
  for (const meta of repos) {
    const h = histories[`${meta.owner}/${meta.repo}`] || [];
    const a = snapshotAt(h, start);
    const b = snapshotAt(h, end);
    if (!a || !b || b.date <= a.date) continue;
    const days = (toDate(b.date) - toDate(a.date)) / DAY;
    const gain = b.stars - a.stars;
    rows.push({
      name: `${meta.owner}/${meta.repo}`,
      notes: meta.notes || "",
      stars: b.stars,
      gain,
      perDay: gain / days,
      pct: a.stars >= MIN_STARS_FOR_PCT ? (gain / a.stars) * 100 : null,
    });
  }
  const added = repos
    .filter((r) => r.added && r.added >= start && r.added < end)
    .map((r) => ({ name: `${r.owner}/${r.repo}`, notes: r.notes || "", starsAtAdd: r.stars_at_add }));
  return {
    start,
    end,
    measured: rows.length,
    totalGain: rows.reduce((s, r) => s + r.gain, 0),
    byGain: [...rows].sort((x, y) => y.gain - x.gain).slice(0, TOP_N),
    byPct: rows.filter((r) => r.pct !== null).sort((x, y) => y.pct - x.pct).slice(0, TOP_N),
    added,
  };
}

// ---- Markdown ----
const fmt = (n) => Math.round(n).toLocaleString("en-US");
const link = (name) => `[${name}](https://github.com/${name})`;
const short = (s) => (s.length > 80 ? s.slice(0, 77) + "…" : s).replace(/\|/g, "\\|");

function renderReport(label, s) {
  const lines = [
    `# Rising repos — ${label}`,
    "",
    `Week ${s.start} to ${addDays(s.end, -1)} (UTC). Stars measured from the daily snapshot on ${s.start} to the one on ${s.end}.`,
    "",
    `${s.measured} repos with data for the whole week gained **${fmt(s.totalGain)}** stars in total.`,
    "",
    `## Top ${TOP_N} by stars gained`,
    "",
    "| # | Repo | Stars gained | Per day | Total | What it is |",
    "|---|---|---:|---:|---:|---|",
    ...s.byGain.map((r, i) => `| ${i + 1} | ${link(r.name)} | +${fmt(r.gain)} | +${fmt(r.perDay)} | ${fmt(r.stars)} | ${short(r.notes)} |`),
    "",
    `## Top ${TOP_N} by growth rate`,
    "",
    `Repos with at least ${fmt(MIN_STARS_FOR_PCT)} stars at the start of the week.`,
    "",
    "| # | Repo | Growth | Stars gained | Total |",
    "|---|---|---:|---:|---:|",
    ...s.byPct.map((r, i) => `| ${i + 1} | ${link(r.name)} | +${r.pct.toFixed(1)}% | +${fmt(r.gain)} | ${fmt(r.stars)} |`),
    "",
    "## Newly tracked this week",
    "",
    ...(s.added.length
      ? s.added.map((r) => `- ${link(r.name)}${r.starsAtAdd ? ` — ${fmt(r.starsAtAdd)} stars when added` : ""}${r.notes ? ` — ${short(r.notes)}` : ""}`)
      : ["None."]),
    "",
    "---",
    "",
    "Generated by [`scripts/weekly-report.js`](../scripts/weekly-report.js) from the data in [`data/`](../data). [All reports](./README.md) · [Live dashboard](https://patrick-creates.github.io/rising-repos-tracker/)",
    "",
  ];
  return lines.join("\n");
}

function renderIndex(labels) {
  return [
    "# Weekly reports",
    "",
    "One report per ISO week: fastest-growing repos by stars gained and by growth rate, plus newly tracked repos. Written automatically every Monday.",
    "",
    ...[...labels].sort().reverse().map((l) => `- [${l}](./${l}.md)`),
    "",
  ].join("\n");
}

// ---- I/O ----
function loadHistories(repos, dataDir) {
  const out = {};
  for (const r of repos) {
    const p = path.join(dataDir, r.owner, r.repo, "history.json");
    if (fs.existsSync(p)) out[`${r.owner}/${r.repo}`] = JSON.parse(fs.readFileSync(p, "utf8"));
  }
  return out;
}

function main() {
  const args = process.argv.slice(2);
  const force = args.includes("--force");
  const weekArg = args[args.indexOf("--week") + 1];

  const repos = JSON.parse(fs.readFileSync("repos.json", "utf8"));
  const histories = loadHistories(repos, "data");
  const latest = Object.values(histories).flat().reduce((m, e) => (e.date > m ? e.date : m), "");
  if (!latest) return console.log("No history data, nothing to report.");

  let week;
  if (args.includes("--week")) {
    const m = /^(\d{4})-W(\d{2})$/.exec(weekArg || "");
    if (!m) throw new Error("--week expects YYYY-Www, e.g. 2026-W43");
    // Monday of ISO week: Jan 4 is always in week 1
    const jan4 = `${m[1]}-01-04`;
    week = isoWeek(addDays(isoWeek(jan4).monday, (Number(m[2]) - 1) * 7));
  } else {
    week = lastCompleteWeek(latest);
  }

  const label = weekLabel(week);
  const file = path.join("reports", `${label}.md`);
  fs.mkdirSync("reports", { recursive: true });
  if (fs.existsSync(file) && !force) {
    console.log(`✓ ${file} exists, skipping (use --force to rewrite)`);
  } else {
    const stats = weekStats(repos, histories, week);
    if (!stats.measured) return console.log(`No repo has data for the whole of ${label}, nothing written.`);
    fs.writeFileSync(file, renderReport(label, stats));
    console.log(`✓ ${file}: ${stats.measured} repos, +${fmt(stats.totalGain)} stars`);
  }

  const labels = fs.readdirSync("reports").filter((f) => /^\d{4}-W\d{2}\.md$/.test(f)).map((f) => f.slice(0, -3));
  fs.writeFileSync(path.join("reports", "README.md"), renderIndex(labels));
}

if (require.main === module) main();

module.exports = { isoWeek, weekLabel, lastCompleteWeek, snapshotAt, weekStats, renderReport, addDays };
